/**
 * RecorderAgent — Event Capture Script (Injected)
 * Ported for Next Gen Automation Studio
 */

// Using string concatenation to avoid template literal parsing issues with Turbopack
export const EVENT_CAPTURE_SCRIPT = [
  "(function initEventCapture() {",
  "  if (window.__recorderAgentInitialized) return;",
  "  window.__recorderAgentInitialized = true;",
  "",
  "  function getCSSPath(el) {",
  "    if (el.id) return '#' + el.id;",
  "    var parts = [];",
  "    var current = el;",
  "    while (current && current.nodeType === Node.ELEMENT_NODE && current !== document.body) {",
  "      var selector = current.tagName.toLowerCase();",
  "      if (current.id) {",
  "        selector = '#' + current.id;",
  "        parts.unshift(selector);",
  "        break;",
  "      }",
  "      var parent = current.parentElement;",
  "      if (parent) {",
  "        var siblings = Array.from(parent.children).filter(function(c) { return c.tagName === current.tagName; });",
  "        if (siblings.length > 1) {",
  "          var idx = siblings.indexOf(current) + 1;",
  "          selector += ':nth-of-type(' + idx + ')';",
  "        }",
  "      }",
  "      parts.unshift(selector);",
  "      current = current.parentElement;",
  "    }",
  "    return parts.join(' > ');",
  "  }",
  "",
  "  function getXPath(el) {",
  '    if (el.id) return \'//\u002a[@id="\' + el.id + \'"]\';',
  "    var parts = [];",
  "    var current = el;",
  "    while (current && current.nodeType === Node.ELEMENT_NODE) {",
  "      var index = 1;",
  "      var sibling = current.previousElementSibling;",
  "      while (sibling) {",
  "        if (sibling.tagName === current.tagName) index++;",
  "        sibling = sibling.previousElementSibling;",
  "      }",
  "      parts.unshift(current.tagName.toLowerCase() + '[' + index + ']');",
  "      current = current.parentElement;",
  "    }",
  "    return '/' + parts.join('/');",
  "  }",
  "",
  "  function getElementInfo(el) {",
  "    if (!el || !el.tagName) return null;",
  "    var rect = el.getBoundingClientRect();",
  "    var dataAttributes = {};",
  "    for (var i = 0; i < el.attributes.length; i++) {",
  "      var attr = el.attributes[i];",
  "      if (attr.name.indexOf('data-') === 0) {",
  "        dataAttributes[attr.name.replace('data-', '')] = attr.value;",
  "      }",
  "    }",
  "    return {",
  "      tagName: el.tagName,",
  "      id: el.id || '',",
  "      className: el.className || '',",
  "      name: el.getAttribute('name') || '',",
  "      type: el.getAttribute('type') || '',",
  "      value: el.value || '',",
  "      innerText: (el.innerText || '').substring(0, 100),",
  "      textContent: (el.textContent || '').substring(0, 100),",
  "      placeholder: el.getAttribute('placeholder') || '',",
  "      href: el.getAttribute('href') || '',",
  "      src: el.getAttribute('src') || '',",
  "      ariaLabel: el.getAttribute('aria-label') || '',",
  "      ariaRole: el.getAttribute('role') || '',",
  "      dataTestId: el.getAttribute('data-testid') || el.getAttribute('data-test-id') || '',",
  "      dataAttributes: dataAttributes,",
  "      cssPath: getCSSPath(el),",
  "      xpath: getXPath(el),",
  "      rect: {",
  "        x: Math.round(rect.x),",
  "        y: Math.round(rect.y),",
  "        width: Math.round(rect.width),",
  "        height: Math.round(rect.height)",
  "      },",
  "      isVisible: rect.width > 0 && rect.height > 0,",
  "      pageUrl: window.location.href",
  "    };",
  "  }",
  "",
  "  function shouldIgnore(el) {",
  "    if (!el) return true;",
  "    if (el.closest('[data-recorder-ignore]')) return true;",
  "    if (el.tagName === 'HTML' || el.tagName === 'BODY') return true;",
  "    return false;",
  "  }",
  "",
  "  function sendEvent(eventData) {",
  "    if (window.__recorderAgent__sendEvent) {",
  "      window.__recorderAgent__sendEvent(JSON.stringify(eventData));",
  "    }",
  "  }",
  "",
  "  var lastClickTime = 0;",
  "  document.addEventListener('click', function(e) {",
  "    var now = Date.now();",
  "    if (now - lastClickTime < 200) return;",
  "    lastClickTime = now;",
  "    var el = e.target;",
  "    if (shouldIgnore(el)) return;",
  "    sendEvent({",
  "      type: 'click',",
  "      timestamp: now,",
  "      elementInfo: getElementInfo(el),",
  "      coordinates: { x: e.clientX, y: e.clientY }",
  "    });",
  "  }, true);",
  "",
  "  document.addEventListener('dblclick', function(e) {",
  "    var el = e.target;",
  "    if (shouldIgnore(el)) return;",
  "    sendEvent({",
  "      type: 'dblclick',",
  "      timestamp: Date.now(),",
  "      elementInfo: getElementInfo(el),",
  "      coordinates: { x: e.clientX, y: e.clientY }",
  "    });",
  "  }, true);",
  "",
  "  var inputDebounce = {};",
  "  document.addEventListener('input', function(e) {",
  "    var el = e.target;",
  "    if (shouldIgnore(el)) return;",
  "    if (['INPUT', 'TEXTAREA', 'SELECT'].indexOf(el.tagName) === -1) return;",
  "    var key = getCSSPath(el);",
  "    clearTimeout(inputDebounce[key]);",
  "    inputDebounce[key] = setTimeout(function() {",
  "      sendEvent({",
  "        type: el.tagName === 'SELECT' ? 'select' : 'type',",
  "        timestamp: Date.now(),",
  "        elementInfo: getElementInfo(el),",
  "        value: el.type === 'password' ? '***' : el.value",
  "      });",
  "    }, 500);",
  "  }, true);",
  "",
  "  document.addEventListener('change', function(e) {",
  "    var el = e.target;",
  "    if (shouldIgnore(el)) return;",
  "    if (el.type === 'checkbox' || el.type === 'radio') {",
  "      sendEvent({",
  "        type: 'check',",
  "        timestamp: Date.now(),",
  "        elementInfo: getElementInfo(el),",
  "        value: el.checked ? 'true' : 'false'",
  "      });",
  "    } else if (el.tagName === 'SELECT') {",
  "      sendEvent({",
  "        type: 'select',",
  "        timestamp: Date.now(),",
  "        elementInfo: getElementInfo(el),",
  "        value: el.value,",
  "        selectedText: el.options[el.selectedIndex] ? el.options[el.selectedIndex].text : ''",
  "      });",
  "    }",
  "  }, true);",
  "",
  "  document.addEventListener('keydown', function(e) {",
  "    if (['Enter', 'Escape', 'Tab'].indexOf(e.key) !== -1) {",
  "      var el = e.target;",
  "      if (shouldIgnore(el)) return;",
  "      sendEvent({",
  "        type: 'keypress',",
  "        timestamp: Date.now(),",
  "        elementInfo: getElementInfo(el),",
  "        key: e.key,",
  "        modifiers: {",
  "          ctrl: e.ctrlKey,",
  "          shift: e.shiftKey,",
  "          alt: e.altKey,",
  "          meta: e.metaKey",
  "        }",
  "      });",
  "    }",
  "  }, true);",
  "",
  "  console.log('[RecorderAgent] Event capture initialized');",
  "})();"
].join("\n");
