import uuid
from typing import List, Dict, Any

class RulesetRegistry:
    """
    Immutable Versioned Ruleset Registry (The OS Disk).
    Stores and versions the Proof Logic generated by SEPS.
    """
    def __init__(self):
        self.active_version = "v1.0"
        self.candidates: Dict[str, Any] = {}
        self.pushed_rulesets: Dict[str, Any] = {"v1.0": []}

    async def register_candidate(self, version: str, rules: List[Dict]):
        self.candidates[version] = rules
        print(f"📦 Registry: Candidate version {version} registered for validation.")

    async def promote_to_active(self, version: str):
        if version in self.candidates:
            self.active_version = version
            self.pushed_rulesets[version] = self.candidates.pop(version)
            print(f"🚀 Registry: Version {version} is now ACTIVE in Production.")

class SEPSLearningLoop:
    """
    The Closed Learning Loop (The Heart of SEPS).
    Validates candidate rules via the Replay Engine.
    """
    def __init__(self, analyzer, induction, replay_engine, registry):
        self.analyzer = analyzer
        self.induction = induction
        self.replay = replay_engine
        self.registry = registry

    async def run_one_cycle(self, tenant_id: uuid.UUID):
        """
        Executes a full self-evolution cycle.
        """
        # 1. ANALYZE
        gaps = await self.analyzer.identify_safety_gaps(tenant_id)
        report = await self.analyzer.generate_vulnerability_report(gaps)
        
        # 2. INDUCE
        candidate_v = await self.induction.induce_new_ruleset(report)
        
        # 3. REPLAY VALIDATE (Regression testing)
        success = await self.replay.reconstruct_graph_at_timestamp(tenant_id, "HISTORICAL_FAIL_T")
        
        # 4. PROMOTE
        if success:
            await self.registry.promote_to_active(candidate_v)
            return {"status": "EVOLVED", "new_version": candidate_v}
        
        return {"status": "ROLLBACK", "reason": "REPLAY_VALIDATION_FAILED"}
